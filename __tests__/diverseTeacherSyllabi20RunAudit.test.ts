describe('Diverse Teacher Syllabi 20-Run Deterministic Ingestion Suite', () => {
  const parser = LocalSyllabusParser.shared;
  const manager = SyllabusImportManager.shared;

  // We test all 5 diverse teacher archetypes
  it('1. Teacher 1 (Sarah Fisher Style): Decimal grading, multi-part rubrics, APA citations, work blocks', () => {
    const raw = TEACHER_1_SIMPLESYLLABUS_DECIMAL;
    const dto = parser.parseText(raw);

    expect(dto.courseCode).toBe('CPC 529');
    expect(dto.courseName).toMatch(/Psychological Assessment/i);
    expect(dto.assignments?.length).toBe(5);

    // Assert weights sum to 100% exactly
    const weights = dto.assignments!.map(a => parseFloat(a.weightPercentage?.replace('%', '') || '0'));
    const sum = weights.reduce((a, b) => a + b, 0);
    expect(sum).toBeCloseTo(100, 2);

    // Multi-part assignments disambiguated
    expect(dto.assignments!.map(a => a.title)).toEqual([
      'Introductory Practicum Survey',
      'Standardized Battery Synthesis',
      'Clinical Assessment PART 1: The Diagnostic Report',
      'Clinical Assessment PART 2: Peer Consultation Evaluation',
      'Clinical Assessment PART 3: Practical Competencies Evaluation'
    ]);

    // Check rubrics mapped
    expect(dto.assignments![1].rubricCriteria?.length).toBe(5);
    expect(dto.assignments![2].rubricCriteria?.length).toBe(6);
    expect(dto.assignments![3].rubricCriteria?.length).toBe(4);
    expect(dto.assignments![4].rubricCriteria?.length).toBe(5);

    // Schedule: 12 weeks
    expect(dto.weeks?.length).toBe(12);

    // Break / work block weeks have 0 readings
    const wk5 = dto.weeks?.find(w => w.weekNumber === 5);
    expect(wk5?.readings?.length).toBe(0);
    const wk7 = dto.weeks?.find(w => w.weekNumber === 7);
    expect(wk7?.readings?.length).toBe(0);

    // Normalize through SyllabusImportManager
    const normalized = manager.normalizeAndValidateSyllabusPayload(dto, raw);
    expect(normalized.candidateAssignments.length).toBe(5);
    const cleanA = manager.deduplicateAssignments(normalized.candidateAssignments, normalized.termYear, normalized.weekDateMap);
    expect(cleanA.length).toBe(5);
    const cleanR = manager.deduplicateReadings(normalized.candidateReadings, normalized.textbooks, normalized.termYear);
    expect(cleanR.length).toBeGreaterThanOrEqual(15);
  });

  it('2. Teacher 2 (Dr. Ron Manley Style): Tabular schedule, semicolon splits, break weeks', () => {
    const raw = TEACHER_2_MANLEY_TRAUMA_TABLE;
    const dto = parser.parseText(raw);

    expect(dto.courseCode).toBe('CPC 532');
    expect(dto.courseName).toMatch(/Traumatology/i);
    expect(dto.weeks?.length).toBe(10);

    // Paper assignment extracted from table deliverable
    expect(dto.assignments?.length).toBe(1);
    expect(dto.assignments?.[0].title).toBe('Language and Violence Analysis/Psychotherapy for Trauma Paper');
    expect(dto.assignments?.[0].weekNumber).toBe(6);
    expect(dto.assignments?.[0].dueDate).toBe('2026-11-15');

    // Break weeks have 0 readings
    const wk7 = dto.weeks?.find(w => w.weekNumber === 7);
    expect(wk7?.readings?.length).toBe(0);
    const wk8 = dto.weeks?.find(w => w.weekNumber === 8);
    expect(wk8?.readings?.length).toBe(0);

    // Textbooks
    expect(dto.textbooks?.length).toBe(3);
  });

  it('3. Teacher 3 (Prof. Marcus Vance Style): Technical engineering, continuous deliverables, RFCs & whitepapers', () => {
    const raw = TEACHER_3_VANCE_ENGINEERING;
    const dto = parser.parseText(raw);

    expect(dto.courseCode).toBe('DATA 635');
    expect(dto.courseName).toMatch(/Cloud Native Machine Learning/i);
    expect(dto.assignments?.length).toBe(4);

    const weights = dto.assignments!.map(a => parseFloat(a.weightPercentage?.replace('%', '') || '0'));
    const sum = weights.reduce((a, b) => a + b, 0);
    expect(sum).toBe(100);

    expect(dto.weeks?.length).toBe(11);
    expect(dto.weeks?.[1]?.readings?.map(r => r.title)).toContain('Feast Architecture Specs');
    expect(dto.weeks?.[2]?.readings?.map(r => r.title)).toContain('Li et al. (2020)');
  });

  it('4. Teacher 4 (Prof. Diane Gehart Style): Dual-Table Architecture with Zero Cross-Bleed', () => {
    const raw = TEACHER_4_DUAL_TABLE_FAMILY;
    const dto = parser.parseText(raw);

    expect(dto.courseCode).toBe('CPC 518');
    expect(dto.courseName).toMatch(/Family Systems/i);
    expect(dto.assignments?.length).toBe(2);

    // Module readings (Table 1: 10 overarching curriculum modules)
    expect(dto.moduleReadings?.length).toBe(10);
    dto.moduleReadings?.forEach(r => {
      expect(r.dueDate).toBeNull();
      expect(r.moduleNumber).toBeDefined();
    });

    // Weekly schedule (Table 2: 12 weekly calendar sessions)
    expect(dto.weeks?.length).toBe(12);
    const wk6 = dto.weeks?.find(w => w.weekNumber === 6);
    expect(wk6?.readings?.length).toBe(0);
    const wk12 = dto.weeks?.find(w => w.weekNumber === 12);
    expect(wk12?.readings?.length).toBe(0);

    // Zero cross-bleed: weekly calendar schedule readings exist
    const weekReadings = dto.weeks?.flatMap(w => w.readings || []) || [];
    expect(weekReadings.length).toBeGreaterThan(0);
  });

  it('5. Teacher 5 (Dr. Amara Lugones Style): Pure Module Humanities (Zero Fabricated Weeks)', () => {
    const raw = TEACHER_5_PURE_MODULE_HUMANITIES;
    const dto = parser.parseText(raw);

    expect(dto.courseCode).toBe('GSP 415');
    expect(dto.courseName).toMatch(/Gender/i);

    // Pure module syllabus must have 0 fabricated weeks (Rule 8)
    expect(dto.weeks?.length || 0).toBe(0);

    // 10 pure module readings
    expect(dto.moduleReadings?.length).toBe(10);
    dto.moduleReadings?.forEach(r => {
      expect(r.moduleNumber).toBeGreaterThanOrEqual(1);
      expect(r.moduleNumber).toBeLessThanOrEqual(10);
      expect(r.dueDate).toBeNull();
    });

    // 10 module deliverables
    expect(dto.assignments?.length).toBe(10);
    expect(dto.assignments?.[0].title).toContain('Historical Genealogies of Norms');
    expect(dto.assignments?.[9].title).toContain('Abolitionist Kinship Manifesto');
  });
});
